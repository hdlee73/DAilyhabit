    /** 요일별 가정 기도 (앱에서 지은 기도) */
    private val family: List<PrayerItem> = DayOfWeek.entries.map { dow ->
        val p = FamilyPrayers.forDate(LocalDate.now().with(dow))
        PrayerItem(
            "family_${dow.value}",
            p.title,
            "가정 기도",
            p.text,
            note = "${listOf("월", "화", "수", "목", "금", "토", "일")[dow.value - 1]}요일 · 앱에서 지은 가정 기도입니다.",
        )
    } + PrayerItem("holy_family", FamilyPrayers.holyFamily.title, "가정 기도", FamilyPrayers.holyFamilyText())

    val all: List<PrayerItem> get() = base + family

    fun byId(id: String): PrayerItem? = all.firstOrNull { it.id == id }

